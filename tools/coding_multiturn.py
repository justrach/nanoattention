#!/usr/bin/env python3
"""Synthetic repository-context coding conversation; not a broad quality benchmark.

Run --native and --reference as SEPARATE processes, in that order. The native
process owns one `flint session CHECKPOINT --context 32768 --mlx-attention 1
--staged-row-tile 2` child. It sends JSONL {id,tokens:[NEW suffix IDs],max_tokens,
reset:false,return_logits:true}; generated tokens, INCLUDING EOS, must already
be committed to KV. No HTTP, model conversion, network, or generated-code execution.

Boundary protocol: render the complete conversation using the checkpoint's local
apply_chat_template, both as bytes and IDs. Preserve every native-generated ID.
Decode with special tokens and cleanup disabled; verify exact re-encoding. Try
assistant content with/without the final EOS (templates often insert it). Accept
only a complete template rendering whose bytes AND IDs start with the entire
cached history. Canonical template closure not generated by a length-limited
assistant is sent as part of the next NEW suffix. Before every subsequent request,
strictly compare the full cached prefix again. Unsupported templates/tokenizer
round trips fail closed: NEVER reset, truncate KV, or replay cached IDs. Reports
record actual lengths, not a claim of exact target sizing. Reference teacher-forces
the exact recorded IDs one token at a time, preserving one stock MLX FP32 cache.
Only final-prefill and final-committed-generation all-vocabulary logits are checked.
"""
