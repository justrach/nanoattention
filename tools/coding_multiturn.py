for _name, _value in {
    "HF_HUB_OFFLINE": "1", "TRANSFORMERS_OFFLINE": "1",
    "HF_HUB_DISABLE_TELEMETRY": "1", "TOKENIZERS_PARALLELISM": "false",
}.items():
    os.environ[_name] = _value

PROTOCOL = "strict-full-template-prefix-v1"
TURNS = [
    "Implement a pure Python function plan_order(graph). graph maps task-name strings "
    "to lists of prerequisite task-name strings. Return a deterministic topological "
    "order with every prerequisite before its dependent. Use only the standard "
    "library. Give the complete implementation in one Python code fence.",
    "Revise plan_order(graph): a dependency absent from the mapping must raise "
    "ValueError; any cycle (including a self-cycle) must also raise ValueError. "
    "Repeated dependency entries count only once. Include disconnected tasks and "
    "return [] for an empty graph. Return the complete revised implementation.",
    "Final revision: never mutate the input dictionary or any dependency list. "
    "When several tasks are ready, always select the lexicographically smallest "
    "currently ready task, yielding the lexicographically smallest topological "
    "ordering. Preserve missing-dependency and cycle errors. Return the complete "
    "pure Python plan_order(graph) implementation in one Python code fence.",
]


class ProtocolError(ValueError):
    pass


def token_ids(value, allow_empty=False):
    if not isinstance(value, list) or (not value and not allow_empty):
        raise ProtocolError("expected a token ID list")
    if any(type(x) is not int or not 0 <= x < 2 ** 32 for x in value):
        raise ProtocolError("invalid token ID")
    return list(value)


def eos_token_ids(tokenizer):
    raw = getattr(tokenizer, "_flint_eos_token_ids", None)
    if raw is None:
        raw = getattr(tokenizer, "eos_token_id", None)
    return token_ids(list(raw) if isinstance(raw, (list, tuple)) else [raw])


def encode(tokenizer, text):
    return token_ids(list(tokenizer.encode(text, add_special_tokens=False)), True)


def render(tokenizer, messages, generation):
    kwargs = dict(add_generation_prompt=generation)
    text = tokenizer.apply_chat_template(messages, tokenize=False, **kwargs)
    ids = token_ids(list(tokenizer.apply_chat_template(
        messages, tokenize=True, return_dict=False, **kwargs)))
    if not isinstance(text, str) or encode(tokenizer, text) != ids:
        raise ProtocolError("template text/ID encoding disagreement")
    return text, ids


def assert_prefix(full, cached, description):
    if len(full) < len(cached) or full[:len(cached)] != cached:
        raise ProtocolError("cached {} prefix mismatch; refusing reset/replay".format(description))


class Conversation:
    def __init__(self, tokenizer):
        self.tokenizer = tokenizer
        self.messages = []
        self.cached_ids = []
        self.cached_text = ""
        self.pending = None

    def user(self, content):
        if self.pending is not None:
            raise ProtocolError("uncommitted assistant turn")
        messages = self.messages + [{"role": "user", "content": content}]
        text, ids = render(self.tokenizer, messages, True)
        assert_prefix(ids, self.cached_ids, "token")
        assert_prefix(text.encode("utf-8"), self.cached_text.encode("utf-8"), "byte")
        suffix = ids[len(self.cached_ids):]
        token_ids(suffix)
        boundary = {
            "protocol": PROTOCOL, "cached_prefix_tokens": len(self.cached_ids),
            "cached_prefix_bytes": len(self.cached_text.encode("utf-8")),
            "full_render_tokens": len(ids), "new_suffix_tokens": len(suffix),
            "strict_id_prefix_verified": True, "strict_byte_prefix_verified": True,
            "render_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
        }
        self.pending = (messages, text, ids)
        return suffix, boundary

    def assistant(self, generated, need_next=True):
        token_ids(generated)
        if self.pending is None:
            raise ProtocolError("assistant without pending user")
        messages, text, ids = self.pending
        decoded = self.tokenizer.decode(generated, skip_special_tokens=False,
                                        clean_up_tokenization_spaces=False)
        # Always commit the raw history first, even if template continuation fails.
        self.cached_ids = ids + generated
        self.cached_text = text + decoded
        self.pending = None
        if encode(self.tokenizer, decoded) != generated:
            if need_next:
                raise ProtocolError("assistant special-token decode round trip is lossy")
            return decoded, {"assistant_roundtrip_verified": False}
        variants = []
        if generated[-1] in eos_token_ids(self.tokenizer):
            variants.append((self.tokenizer.decode(
                generated[:-1], skip_special_tokens=False,
                clean_up_tokenization_spaces=False), True))
        variants.append((decoded, False))
        for content, omitted_eos in variants:
            candidate = messages + [{"role": "assistant", "content": content}]
            completed_text, completed_ids = render(self.tokenizer, candidate, False)
            try:
                assert_prefix(completed_ids, self.cached_ids, "token")
                assert_prefix(completed_text.encode("utf-8"),
                              self.cached_text.encode("utf-8"), "byte")
            except ProtocolError:
                continue
            self.messages = candidate
            return decoded, {
                "assistant_roundtrip_verified": True,
                "terminal_eos_supplied_by_template": omitted_eos,
                "canonical_closure_tokens_not_yet_cached": len(completed_ids) - len(self.cached_ids),
            }
        if need_next:
            raise ProtocolError("assistant/template boundary mismatch; refusing reset/replay")
        return decoded, {"assistant_roundtrip_verified": True,
                         "canonical_assistant_boundary_verified": False}


def repository_context(count):
    """Unique structured modules/specs, not a repeated raw-code token fixture."""
    records = [
        "SYNTHETIC SOURCE/CONTEXT: the following repository is invented for this "
        "context-length exercise, not retrieved production code or a quality benchmark.\n"
        "Repository: orchard_build/ -- a task scheduler with independently described "
        "build targets. The requested function belongs in scheduler.py, not in each "
        "component below. graph values are prerequisites, not successors. All names "
        "are strings. No filesystem, network, package installs, or code execution.\n"
        "SPEC scheduler.py: plan_order(graph) returns a list of task names; callers "
        "own all mappings/lists. Component records below are context only.\n"
    ]
    for i in range(count):
        parent = max(0, i - 1 - (i % 7))
        stage = ("extract", "normalize", "compile", "validate", "package")[i % 5]
        name = "{}_target_{:04d}".format(stage, i)
        records.append(
            "\n--- component/{i:04d}_{stage}.py ---\n"
            "# Component {i}: region={region}, shard={shard}; owner team_{team}.\n"
            "TASK_NAME = {name!r}\n"
            "INPUT_ARTIFACT = 'artifact_{parent:04d}.json'\n"
            "OUTPUT_ARTIFACT = 'artifact_{i:04d}.json'\n"
            "def describe_{i:04d}(metadata):\n"
            "    return {{'task': TASK_NAME, 'revision': {rev},\n"
            "            'input': INPUT_ARTIFACT, 'output': OUTPUT_ARTIFACT,\n"
            "            'enabled': metadata.get('feature_{i:04d}', True)}}\n"
            "[manifest targets.{name}]\n"
            "description = '{stage} shard {shard} in region {region}'\n"
            "retry_budget = {retry}\n"
            "dependency_fixture = ['seed_{parent:04d}', 'shared_{shared:03d}']\n"
            "acceptance = 'emit artifact_{i:04d}; preserve caller metadata; "
            "stable result on repeated planning'\n"
            "review_note = 'record {i} tests a distinct component, not a scheduler "
            "implementation; use the user request as the function contract'\n".format(
                i=i, parent=parent, stage=stage, name=name, region=i % 13,
                shard=(i * 17) % 101, team=i % 19, rev=i * 3 + 1,
                retry=i % 4, shared=(i * 11) % 97))
    return "".join(records)


def build_first_turn(tokenizer, target):
    """Nearest whole-component prefix to the requested *chat* token target."""
    def candidate(count):
        text = repository_context(count) + "\nUSER TASK:\n" + TURNS[0]
        _, ids = render(tokenizer, [{"role": "user", "content": text}], True)
        return text, len(ids)
    low, high = 0, 1
    while candidate(high)[1] < target:
        high *= 2
        if high > 65536:
            raise ProtocolError("target exceeds bounded synthetic repository builder")
    while high - low > 1:
        middle = (low + high) // 2
        if candidate(middle)[1] < target:
            low = middle
        else:
            high = middle
    choices = [(n, candidate(n)) for n in sorted(set([low, high]))]
    count, (text, actual) = min(choices, key=lambda item: abs(item[1][1] - target))
    return text, {"target_prompt_tokens": target, "actual_prompt_tokens": actual,
                  "synthetic_components": count, "source_context": "synthetic",
                  "sizing": "nearest complete structured component; no raw token repetition/truncation"}


class NativeSession:
    """Own exactly one subprocess, with bounded exchanges and cleanup on BaseException."""
    def __init__(self, command, timeout=900, popen=subprocess.Popen):
        self.command = command
        self.timeout = timeout
        self.popen = popen
        self.process = None
        self.stderr = None

    def __enter__(self):
        self.stderr = tempfile.TemporaryFile(mode="w+b")
        try:
            self.process = self.popen(self.command, stdin=subprocess.PIPE,
                                      stdout=subprocess.PIPE, stderr=self.stderr,
                                      text=True, encoding="utf-8", start_new_session=False)
        except BaseException:
            self.stderr.close()
            raise
        return self

    def request(self, payload):
        if self.process is None or self.process.poll() is not None:
            raise ProtocolError("native session is not running")
        result = queue.Queue(maxsize=1)
        def exchange():
            try:
                self.process.stdin.write(json.dumps(payload, separators=(",", ":")) + "\n")
                self.process.stdin.flush()
                line = self.process.stdout.readline()
                if not line:
                    raise ProtocolError("native session ended before response")
                result.put((True, json.loads(line)))
            except BaseException as error:
                result.put((False, error))
        worker = threading.Thread(target=exchange, daemon=True)
        worker.start()
        try:
            ok, value = result.get(timeout=self.timeout)
            if not ok:
                raise ProtocolError("native JSONL exchange failed") from value
            return value
        except queue.Empty:
            raise ProtocolError("native JSONL exchange timed out")

    def close(self, graceful=False):
        process = self.process
        if process is not None:
            if graceful and process.poll() is None:
                # EOF lets the native caller run Model/Metal cleanup normally.
                process.stdin.close()
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    pass
            # The native worker has no children. Keep it in the caller's group
            # so guarded_run can stop the entire owned job on outer interruption.
            # Locally terminate only this child, never the caller/user shell.
            # Stop a blocked exchange writer before closing its pipe.
            if process.poll() is None:
                try:
                    process.terminate()
                except ProcessLookupError:
                    pass
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    try:
                        process.kill()
                    except ProcessLookupError:
                        pass
                    process.wait(timeout=5)
            for stream in (process.stdin, process.stdout):
                if stream is not None:
                    stream.close()
            self.process = None
        if self.stderr is not None:
            self.stderr.close()
            self.stderr = None
        if graceful and process is not None and process.returncode != 0:
            raise ProtocolError("native session exited abnormally after EOF")

    def __exit__(self, *exception):
        self.close(graceful=not exception or exception[0] is None)


def validate_response(response, request, before, context, np):
    if not isinstance(response, dict) or response.get("id") != request["id"]:
        raise ProtocolError("native response ID mismatch")
    generated = token_ids(response.get("tokens"))
    if len(generated) > request["max_tokens"]:
        raise ProtocolError("native exceeded generation budget")
    after = before + len(request["tokens"]) + len(generated)
    expected = {"cache_before": before, "cache_after": after,
                "prefill_tokens": len(request["tokens"]),
                "decode_forward_tokens": len(generated), "reused_prefix_tokens": before}
    for name, value in expected.items():
        if type(response.get(name)) is not int or response[name] != value:
            raise ProtocolError("invalid native {} accounting".format(name))
    if after > context or type(response.get("eos")) is not bool:
        raise ProtocolError("native context/EOS contract violation")
    for name in ("prefill_seconds", "decode_seconds"):
        value = response.get(name)
        if type(value) not in (int, float) or not math.isfinite(value) or value < 0:
            raise ProtocolError("invalid native timing")
    for name in ("kv_allocated_bytes", "kv_valid_bytes"):
        if type(response.get(name)) is not int or response[name] < 0:
            raise ProtocolError("invalid native KV byte accounting")
    if response["kv_valid_bytes"] > response["kv_allocated_bytes"]:
        raise ProtocolError("native valid KV exceeds allocation")
    arrays = {}
    for name in ("prefill_logits", "final_logits"):
        raw = response.get(name)
        if not isinstance(raw, list) or not raw or any(type(v) not in (int, float) for v in raw):
            raise ProtocolError("invalid all-vocabulary logits")
        array = np.asarray(raw, dtype=np.float32)
        if array.ndim != 1 or not np.isfinite(array).all():
            raise ProtocolError("nonfinite or invalid boundary logits")
        arrays[name] = array
    if arrays["prefill_logits"].shape != arrays["final_logits"].shape:
        raise ProtocolError("boundary vocabulary size mismatch")
    if any(x >= arrays["prefill_logits"].size for x in request["tokens"] + generated):
        raise ProtocolError("token exceeds logit vocabulary")
    if int(arrays["prefill_logits"].argmax()) != generated[0]:
        raise ProtocolError("native first generated token is not prefill greedy top1")
    return arrays


def syntax_status(text):
    """Parse only; never import/compile/execute model-produced code."""
    fences = re.findall(r"```(?:python|py)?[ \t]*\n(.*?)```", text, re.DOTALL)
    source = fences[-1] if fences else text
    try:
        tree = ast.parse(source)
    except (SyntaxError, ValueError, RecursionError):
        return {"syntax": "invalid", "functional": "not_tested", "executed": False}
    found = any(isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
                and node.name == "plan_order" for node in tree.body)
    return {"syntax": "valid", "has_plan_order_definition": found,
            "functional": "not_tested", "executed": False}


def final_answer(tokenizer, generated):
    """Separate final text from Flint reasoning; never grade code inside thoughts."""
    start, end = encode(tokenizer, "<think>"), encode(tokenizer, "</think>")
    offset = 0
    if start and generated[:len(start)] == start:
        for i in range(len(start), len(generated) - len(end) + 1):
            if end and generated[i:i+len(end)] == end:
                offset = i + len(end)
                break
        else:
            return "", False
    return tokenizer.decode(generated[offset:], skip_special_tokens=True,
                            clean_up_tokenization_spaces=False), True


def save_json(path, value):
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def load_tokenizer(checkpoint):
    from transformers import AutoTokenizer
    tokenizer = AutoTokenizer.from_pretrained(str(checkpoint), local_files_only=True,
                                              trust_remote_code=False, fix_mistral_regex=False)
    tokenizer.chat_template = (checkpoint / "chat_template.jinja").read_text(encoding="utf-8")
    config = json.loads((checkpoint / "config.json").read_text(encoding="utf-8"))
    raw_eos = config.get("eos_token_id", tokenizer.eos_token_id)
    tokenizer._flint_eos_token_ids = token_ids(raw_eos if isinstance(raw_eos, list) else [raw_eos])
    return tokenizer


def native_run(args):
    import numpy as np
    tokenizer = load_tokenizer(args.checkpoint)
    first, sizing = build_first_turn(tokenizer, args.prompt_tokens)
    if sizing["actual_prompt_tokens"] + 3 * args.max_tokens + 1024 > args.context:
        raise ProtocolError("prompt and reserved three-turn budget exceed context")
    args.output.mkdir(parents=True, exist_ok=True)
    transcript_path = args.output / "transcript.json"
    if transcript_path.exists():
        raise ProtocolError("output already contains a transcript; choose a fresh ignored directory")
    transcript = {"schema": 1, "protocol": PROTOCOL, "status": "incomplete",
                  "scope": "synthetic coding context-length exercise; not broad quality evaluation",
                  "context": args.context, "sizing": sizing, "turns": [],
                  "template_sha256": hashlib.sha256(tokenizer.chat_template.encode()).hexdigest(),
                  "native_execution": {"mlx_attention": 1, "staged_row_tile": 2},
                  "conversation_token_ids": []}
    arrays = {}
    conversation = Conversation(tokenizer)
    command = [str(args.binary.resolve()), "session", str(args.checkpoint.resolve()),
               "--context", str(args.context), "--mlx-attention", "1", "--staged-row-tile", "2"]
    try:
        with NativeSession(command, args.timeout) as native:
            for index, content in enumerate([first] + TURNS[1:]):
                suffix, boundary = conversation.user(content)
                before = len(conversation.cached_ids)
                if before + len(suffix) + args.max_tokens > args.context:
                    raise ProtocolError("new turn exceeds context; refusing cache truncation")
                request = {"id": index + 1, "tokens": suffix, "max_tokens": args.max_tokens,
                           "reset": False, "return_logits": True}
                response = native.request(request)
                logits = validate_response(response, request, before, args.context, np)
                if response["eos"] != (response["tokens"][-1] in eos_token_ids(tokenizer)):
                    raise ProtocolError("native EOS disagrees with local tokenizer")
                metadata = {name: value for name, value in response.items()
                            if name in ("id", "tokens", "eos", "cache_before", "cache_after",
                                        "prefill_tokens", "decode_forward_tokens", "reused_prefix_tokens",
                                        "prefill_seconds", "decode_seconds", "kv_allocated_bytes", "kv_valid_bytes")}
                decoded = tokenizer.decode(response["tokens"], skip_special_tokens=False,
                                           clean_up_tokenization_spaces=False)
                answer, reasoning_complete = final_answer(tokenizer, response["tokens"])
                record = {"request": request, "response": metadata, "user_text": content,
                          "assistant_text": decoded, "final_answer_text": answer, "boundary": boundary,
                          "completion": {"stop_reason": "eos" if response["eos"] else "length_limit",
                                         "reasoning_complete": reasoning_complete,
                                         "has_final_answer": bool(answer.strip())},
                          "static_check": syntax_status(answer) if answer.strip() else
                              {"syntax": "not_checked_no_final_answer", "functional": "not_tested", "executed": False}}
                transcript["turns"].append(record)
                for name, array in logits.items():
                    arrays["turn_{}_{}".format(index + 1, name)] = array
                # Preserve IDs even if rendering the assistant fails closed below.
                transcript["conversation_token_ids"].extend(suffix + response["tokens"])
                _, completion = conversation.assistant(response["tokens"], need_next=index < 2)
                record["boundary"].update(completion)
                print("\n=== Assistant turn {} ===\n{}".format(index + 1, decoded), flush=True)
        transcript["status"] = "complete"
    except BaseException as error:
        # Sanitized: no paths, arbitrary exception messages, host/model/session IDs.
        transcript["failure_type"] = type(error).__name__
        raise
    finally:
        np.savez(args.output / "boundaries.npz", **arrays)
        save_json(transcript_path, transcript)
    print(json.dumps({"status": transcript["status"], "sizing": sizing,
                      "cache_after": transcript["turns"][-1]["response"]["cache_after"],
                      "functional": "not_tested", "native_child_stopped": True}, indent=2))


def validate_transcript(transcript, boundaries, np):
    """CPU-only validation; run BEFORE importing MLX or loading a reference model."""
    if (transcript.get("schema") != 1 or transcript.get("protocol") != PROTOCOL
            or transcript.get("status") != "complete"):
        raise ProtocolError("reference requires a complete supported transcript")
    turns = transcript.get("turns")
    if not isinstance(turns, list) or len(turns) != 3:
        raise ProtocolError("reference requires all three turns")
    context = transcript.get("context")
    if type(context) is not int or context <= 0:
        raise ProtocolError("invalid recorded context")
    history, expected_keys = [], set()
    vocabulary = None
    for index, turn in enumerate(turns):
        request, response = turn["request"], turn["response"]
        token_ids(request.get("tokens"))
        if (request.get("id") != index + 1 or request.get("reset") is not False
                or request.get("return_logits") is not True
                or type(request.get("max_tokens")) is not int or request["max_tokens"] <= 0):
            raise ProtocolError("invalid recorded incremental request")
        expanded = dict(response)
        for name in ("prefill_logits", "final_logits"):
            key = "turn_{}_{}".format(index + 1, name)
            expected_keys.add(key)
            array = boundaries[key]
            if array.dtype != np.float32 or array.ndim != 1:
                raise ProtocolError("reference boundary must be a float32 vocabulary vector")
            if vocabulary is None:
                vocabulary = len(array)
            if len(array) != vocabulary:
                raise ProtocolError("transcript vocabulary changed")
            expanded[name] = array.tolist()
        validate_response(expanded, request, len(history), context, np)
        boundary = turn.get("boundary", {})
        if (boundary.get("cached_prefix_tokens") != len(history)
                or boundary.get("strict_id_prefix_verified") is not True
                or boundary.get("strict_byte_prefix_verified") is not True
                or boundary.get("new_suffix_tokens") != len(request["tokens"])
                or boundary.get("full_render_tokens") != len(history) + len(request["tokens"])):
            raise ProtocolError("missing or inconsistent strict boundary proof")
        history.extend(request["tokens"] + response["tokens"])
    if set(boundaries.keys()) != expected_keys:
        raise ProtocolError("unexpected/missing boundary arrays")
    if history != token_ids(transcript.get("conversation_token_ids")):
        raise ProtocolError("recorded conversation differs from exact teacher-force stream")
    return turns


def compare_boundary(native, reference, np):
    reference = np.asarray(reference, dtype=np.float32)
    if reference.shape != native.shape or not np.isfinite(reference).all():
        raise ProtocolError("reference logits shape/finiteness mismatch")
    delta = native.astype(np.float64) - reference.astype(np.float64)
    return {"allclose": bool(np.allclose(native, reference, rtol=2e-3, atol=2e-3)),
            "bit_exact": bool(np.array_equal(native.view(np.uint32), reference.view(np.uint32))),
            "greedy_top1_agreement": int(native.argmax()) == int(reference.argmax()),
            "native_top1": int(native.argmax()), "reference_top1": int(reference.argmax()),
            "max_absolute_error": float(np.max(np.abs(delta))),
            "rms_error": float(np.sqrt(np.mean(delta * delta))), "vocabulary_size": int(native.size)}


def sequential_reference(turns, boundaries, forward, np):
    """Pure driver injected with a one-token stock forward, enabling CPU tests."""
    reports, offset = [], 0
    for index, turn in enumerate(turns):
        before = offset
        for token in turn["request"]["tokens"]:
            logits = forward(token)
            offset += 1
        prefill = compare_boundary(boundaries["turn_{}_prefill_logits".format(index + 1)], logits, np)
        greedy_matches = 0
        for token in turn["response"]["tokens"]:
            greedy_matches += int(int(np.asarray(logits).argmax()) == token)
            logits = forward(token)  # Commit even the last generated token/EOS.
            offset += 1
        final = compare_boundary(boundaries["turn_{}_final_logits".format(index + 1)], logits, np)
        if before != turn["response"]["cache_before"] or offset != turn["response"]["cache_after"]:
            raise ProtocolError("reference cache accounting mismatch")
        reports.append({"turn": index + 1, "cache_before": before, "cache_after": offset,
                        "prefill": prefill, "final": final,
                        "teacher_forced_greedy_matches": greedy_matches,
                        "generated_tokens": len(turn["response"]["tokens"])})
    return reports


def reference_run(args):
    import numpy as np
    transcript = json.loads((args.output / "transcript.json").read_text(encoding="utf-8"))
    with np.load(args.output / "boundaries.npz", allow_pickle=False) as saved:
        boundaries = {name: saved[name] for name in saved.files}
    turns = validate_transcript(transcript, boundaries, np)
    # Native is a separate completed invocation, never co-resident with this model.
    import mlx.core as mx
    from mlx_lm import load
    from mlx_lm.models.cache import make_prompt_cache
    mx.set_memory_limit(32 * 1024 ** 3)
    mx.set_cache_limit(512 * 1024 ** 2)
    model, _ = load(str(args.checkpoint), tokenizer_config={"fix_mistral_regex": False})
    # Exactly compare_mlx.py's original FP32 pattern; do not steer expert routing.
    model.set_dtype(mx.float32)
    cache = make_prompt_cache(model)
    def forward(token):
        logits = model(mx.array([[token]], dtype=mx.int32), cache=cache)
        mx.eval(logits)
        return np.array(logits[0, -1], dtype=np.float32)
    reports = sequential_reference(turns, boundaries, forward, np)
    passed = (all(item[boundary]["allclose"] for item in reports for boundary in ("prefill", "final"))
              and all(item["teacher_forced_greedy_matches"] == item["generated_tokens"] for item in reports))
    report = {"status": "pass" if passed else "fail", "reference_prefill_mode": "sequential",
              "precision": "stock MLX model.set_dtype(float32), unchanged expert selection",
              "teacher_forcing": "identical recorded token IDs including final EOS; one persistent cache",
              "rtol": 2e-3, "atol": 2e-3, "boundaries_only": True, "turns": reports,
              "functional": "not_tested", "scope": "synthetic coding context-length exercise"}
    save_json(args.output / "reference.json", report)
    print(json.dumps(report, indent=2))
    if not passed:
        raise ProtocolError("boundary logits or greedy continuation disagree with FP32 reference")


def positive(value):
    number = int(value)
    if not 0 < number < 2 ** 32:
        raise argparse.ArgumentTypeError("must be a positive u32")
    return number


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--native", action="store_true")
    mode.add_argument("--reference", action="store_true")
    parser.add_argument("checkpoint", type=Path)
    parser.add_argument("--binary", type=Path, default=Path(__file__).resolve().parents[1] / "zig-out/bin/flint")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "target/coding-multiturn")
    parser.add_argument("--prompt-tokens", type=positive, default=16384)
    parser.add_argument("--context", type=positive, default=32768)
    parser.add_argument("--max-tokens", type=positive, default=4096,
                        help="per-turn generation budget, including reasoning tokens")
    parser.add_argument("--timeout", type=positive, default=1800, help="seconds per native JSONL exchange")
    args = parser.parse_args(argv)
    ignored_root = Path(__file__).resolve().parents[1] / "target"
    if not args.output.resolve().is_relative_to(ignored_root.resolve()):
        parser.error("--output must be within the git-ignored repository target/ directory")
    if args.native:
        native_run(args)
    else:
        reference_run(args)


if __name__ == "__main__":
    main()
