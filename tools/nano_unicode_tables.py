#!/usr/bin/env python3
"""Write src/mega/unicode_tables.zig: the character classes the native tokenizer's
pre-tokenizer regex needs (src/mega/tokenizer.zig), from a stated Unicode version.

Classes: letter (general category L*), number (N*), space (the White_Space property,
which is what Oniguruma's \\s matches), other. Python's str.isspace set (what a Jinja
`trim` strips) is written too, for the chat templates.

The tokenizers library's regex engine (Oniguruma, tokenizers 0.23.3) uses Unicode
16.0.0: tools/nano_tokenizer_check.py `classes` compares every code point. This script
refuses to run under a Python whose unicodedata is another version (Python 3.14 ships
16.0.0):

    python3.14 -I tools/nano_unicode_tables.py --out src/mega/unicode_tables.zig
"""
import argparse
import sys
import unicodedata

VERSION = "16.0.0"

# PropList.txt White_Space (unchanged since Unicode 6.3, where U+180E left it).
WHITE_SPACE = [(0x09, 0x0D), (0x20, 0x20), (0x85, 0x85), (0xA0, 0xA0), (0x1680, 0x1680),
               (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F),
               (0x3000, 0x3000)]


def classify(cp):
    if any(lo <= cp <= hi for lo, hi in WHITE_SPACE):
        return "space"
    cat = unicodedata.category(chr(cp))
    if cat[0] == "L":
        return "letter"
    if cat[0] == "N":
        return "number"
    return "other"


def ranges(pred):
    out, start = [], None
    for cp in range(0x110001):
        inside = cp <= 0x10FFFF and pred(cp)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    if unicodedata.unidata_version != VERSION:
        sys.exit("this Python's unicodedata is %s; the tables must be Unicode %s (use Python 3.14)"
                 % (unicodedata.unidata_version, VERSION))
    classes = [classify(cp) if not 0xD800 <= cp <= 0xDFFF else "other" for cp in range(0x110000)]
    runs = []
    for cp, c in enumerate(classes):
        if c == "other":
            continue
        if runs and runs[-1][2] == c and runs[-1][1] == cp - 1:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, c])
    pyspace = ranges(lambda cp: chr(cp).isspace())
    lines = [
        "//! Generated by tools/nano_unicode_tables.py from Unicode %s; do not edit." % VERSION,
        "//! Classes for the pre-tokenizer regex: letter = \\p{L}, number = \\p{N},",
        "//! space = White_Space (Oniguruma's \\s), other = everything else.",
        "pub const unicode_version = \"%s\";" % VERSION,
        "pub const Class = enum(u2) { other, letter, number, space };",
        "pub const Range = struct { lo: u21, hi: u21, class: Class };",
        "/// Sorted, disjoint; code points in no range are `other`.",
        "pub const ranges = [_]Range{",
    ]
    for lo, hi, c in runs:
        lines.append("    .{ .lo = 0x%X, .hi = 0x%X, .class = .%s }," % (lo, hi, c))
    lines.append("};")
    lines.append("/// Python's str.isspace (what a Jinja `trim` strips), sorted and disjoint.")
    lines.append("pub const python_space = [_][2]u21{")
    for lo, hi in pyspace:
        lines.append("    .{ 0x%X, 0x%X }," % (lo, hi))
    lines.append("};")
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d class ranges, %d isspace ranges (Unicode %s)" % (args.out, len(runs), len(pyspace), VERSION))


if __name__ == "__main__":
    main()
